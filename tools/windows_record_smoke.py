r"""Recorder smoke test against a window created by this script (never against any other program).

Default (passive, generates NO input): creates its own small window (not activated), verifies it, starts a real
recording with the real low-level observation hooks, waits about a second, stops, and checks that the recorder
completed, released its hooks, and that geometry (window under the point, client origin and size) read by the real
backend matches the window. Any input you happen to make inside THAT window during those seconds is recorded and
printed; input anywhere else is ignored.

    .venv\Scripts\python.exe tools\windows_record_smoke.py

Interactive (only when YOU run it): `--interactive` keeps recording for up to 60 s, so you can click and type in the
test window yourself; press F10 to stop. The recording is printed as JSON. Nothing is ever sent to any window.

    .venv\Scripts\python.exe tools\windows_record_smoke.py --interactive

Why there is no automatic end-to-end input check: a real hook can only be exercised with real hardware-level input,
which would have to be generated by injecting it into the desktop (moving the user's pointer and typing into
whatever has focus). That cannot be made safe, so it is deliberately not done.
"""
from __future__ import annotations

import sys
import time
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
sys.path.insert(0, str(Path(__file__).resolve().parent))

from windows_click_smoke import TestWindow  # noqa: E402  (the dedicated window used by the input smoke test)

from app.core.cancel import EmergencyStop  # noqa: E402
from app.providers.recording import RecorderState  # noqa: E402
from app.providers.recording_format import recording_to_json  # noqa: E402
from app.windows.backend import MouseObservationKind  # noqa: E402
from app.windows.recorder import WindowRecorder  # noqa: E402
from app.windows.target import WindowVerifier  # noqa: E402
from app.windows.win32 import Win32InputBackend, Win32ObservationBackend  # noqa: E402


def main() -> int:
    interactive = "--interactive" in sys.argv
    try:
        import ctypes
        ctypes.windll.user32.SetProcessDpiAwarenessContext(ctypes.c_void_p(-4))
    except Exception:
        pass
    win = TestWindow()
    win.start()
    time.sleep(0.3)
    failures = []
    try:
        stop = EmergencyStop()
        windows = Win32InputBackend()
        verifier = WindowVerifier(windows, stop)
        target = verifier.verify(win.hwnd)
        size = windows.client_size(win.hwnd)
        print(f"VERIFIED dedicated window {target.provider_id}:{target.target_id}, client area {size[0]}x{size[1]}")

        observer = Win32ObservationBackend()
        centre = observer._mouse_observation(win.hwnd, MouseObservationKind.MOVE, 0, 0, False)
        if centre.client_origin is None or centre.client_size != size:
            failures.append(f"client geometry mismatch: {centre.client_origin} {centre.client_size} vs {size}")
        else:
            print(f"geometry OK: client origin (screen) {centre.client_origin}, size {centre.client_size}")
        x, y = centre.client_origin[0] + size[0] // 2, centre.client_origin[1] + size[1] // 2
        probe = observer._mouse_observation(win.hwnd, centre.kind, x, y, False)
        print(f"window under the client centre: {'this test window' if probe.hit_hwnd == win.hwnd else 'another window covers it (fine)'}")

        recorder = WindowRecorder(target, verifier, observer, stop)
        recorder.start()
        print("recording started (real hooks installed)" + ("; click/type in the test window, F10 stops" if interactive else ""))
        deadline = time.monotonic() + (60 if interactive else 1.0)
        while time.monotonic() < deadline and recorder.state is RecorderState.RECORDING:
            time.sleep(0.05)
        if recorder.state is RecorderState.RECORDING:
            recording = recorder.stop()
        else:
            recording = recorder.recording
        if recorder.state is not RecorderState.COMPLETED or recording is None:
            failures.append(f"recorder ended as {recorder.state.value} ({recorder.end_reason})")
        else:
            print(f"recording completed ({recorder.end_reason}): {len(recording)} events, {recording.duration_ms} ms")
            if interactive or len(recording):
                print(recording_to_json(recording))
        observer.stop()
        if observer._active:
            failures.append("observation hooks were not released")
    finally:
        win.close()
    print("PASS" if not failures else "FAIL: " + "; ".join(failures))
    return 0 if not failures else 1


if __name__ == "__main__":
    raise SystemExit(main())
